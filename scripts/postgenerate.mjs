// Runs after `nuxt generate`: computes CSP hashes for inline scripts/styles and writes .output/public/_headers.
import { createHash } from 'node:crypto'
import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs'
import { join } from 'node:path'

const root = new URL('../.output/public', import.meta.url).pathname

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name)
    if (statSync(p).isDirectory()) walk(p, out)
    else if (name.endsWith('.html')) out.push(p)
  }
  return out
}

const sha = s => `'sha256-${createHash('sha256').update(s, 'utf8').digest('base64')}'`
const scriptHashes = new Set()
const styleHashes = new Set()
let styleAttrs = 0
const attrPages = new Set()
const files = walk(root)

const JSON_TYPES = /^(application\/(ld\+)?json|text\/json)$/i
for (const file of files) {
  const html = readFileSync(file, 'utf8')
  for (const m of html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/gi)) {
    const attrs = m[1]
    if (/\bsrc\s*=/i.test(attrs)) continue
    const type = /\btype\s*=\s*["']?([^"'\s>]+)/i.exec(attrs)?.[1]
    if (type && JSON_TYPES.test(type)) continue
    if (!m[2].trim()) continue
    scriptHashes.add(sha(m[2]))
  }
  for (const m of html.matchAll(/<style\b[^>]*>([\s\S]*?)<\/style>/gi)) {
    if (m[1].trim()) styleHashes.add(sha(m[1]))
  }
  const n = (html.match(/\sstyle="/g) || []).length
  if (n) { styleAttrs += n; attrPages.add(file.slice(root.length)) }
}

// Libraries that inject a constant <style> at runtime (not present in the prerendered HTML).
// We extract the exact template-literal text from the built JS so the hash survives upgrades.
const RUNTIME_STYLES = [
  { lib: 'vaul-vue (UDrawer)', start: '`[data-vaul-drawer]{' },
]
const jsDir = join(root, '_nuxt')
const jsFiles = readdirSync(jsDir).filter(f => f.endsWith('.js')).map(f => join(jsDir, f))
for (const { lib, start } of RUNTIME_STYLES) {
  let found = false
  for (const f of jsFiles) {
    const js = readFileSync(f, 'utf8')
    const i = js.indexOf(start)
    if (i === -1) continue
    const end = js.indexOf('`', i + 1)
    const text = js.slice(i + 1, end).replace(/\\(.)/g, '$1') // undo template-literal escapes
    styleHashes.add(sha(text))
    found = true
    break
  }
  if (!found) console.warn(`[postgenerate] runtime style for ${lib} not found in bundle (unused, or its source changed)`)
}

const s = [...scriptHashes].sort()
const st = [...styleHashes].sort()
const csp = [
  "default-src 'self'",
  `script-src 'self' 'wasm-unsafe-eval' ${s.join(' ')}`.trim(),
  `style-src 'self' ${st.join(' ')}`.trim(),
  "style-src-attr 'unsafe-inline'",
  "worker-src 'self' blob:",
  "connect-src 'self'",
  "img-src 'self' blob: data:",
  "media-src 'self' blob:",
  "font-src 'self'",
  "object-src 'none'",
  "base-uri 'none'",
  "frame-ancestors 'none'",
  "form-action 'none'",
  "manifest-src 'self'",
].join('; ')

const headers = `# Generated by scripts/postgenerate.mjs
/*
  Cross-Origin-Opener-Policy: same-origin
  Cross-Origin-Embedder-Policy: require-corp
  Cross-Origin-Resource-Policy: same-origin
  Referrer-Policy: no-referrer
  X-Content-Type-Options: nosniff
  Permissions-Policy: camera=(), microphone=(), geolocation=()
  Content-Security-Policy: ${csp}

/_nuxt/*
  Cache-Control: public, max-age=31536000, immutable
`
writeFileSync(join(root, '_headers'), headers)

console.log(`[postgenerate] ${files.length} HTML files scanned`)
console.log(`[postgenerate] CSP hashes: ${s.length} script, ${st.length} style`)
console.log(`[postgenerate] style="" attributes in HTML: ${styleAttrs}${styleAttrs ? ` (in ${attrPages.size} pages)` : ' -> style-src-attr can be dropped'}`)
console.log('[postgenerate] wrote .output/public/_headers')
